-- ---------------------------------------------------------------------
-- 3. Consultas frecuentes y procesos programados
-- ---------------------------------------------------------------------

-- RF-03: búsqueda de usuarios por nombre y de predios por dirección (prefijo, sin distinguir mayúsculas)
CREATE INDEX IX_USUARIO_NOMBRE          ON USUARIO (UPPER(NOMBRE_COMPLETO));
CREATE INDEX IX_PREDIO_DIRECCION        ON PREDIO (UPPER(DIRECCION));

-- RF-07: facturas e historial de 24 meses de un usuario
CREATE INDEX IX_FACTURA_USUARIO         ON FACTURA (USUARIO_ID, PERIODO DESC);

-- RF-21: job diario que vence facturas PENDIENTES con fecha de vencimiento cumplida
CREATE INDEX IX_FACTURA_VENCIMIENTO     ON FACTURA (ESTADO, FECHA_VENCIMIENTO);

-- SWR-17: cola de sincronización con el ERP (solo indexa lo pendiente)
CREATE INDEX IX_FACTURA_SYNC_ERP        ON FACTURA (CASE WHEN ESTADO_SYNC_ERP <> 'SINCRONIZADA' THEN ESTADO_SYNC_ERP END);
CREATE INDEX IX_PAGO_SYNC_ERP           ON PAGO (CASE WHEN ESTADO_SYNC_ERP <> 'SINCRONIZADA' THEN ESTADO_SYNC_ERP END);

-- P-07: bandeja de crítica de lecturas (solo indexa las que esperan revisión)
CREATE INDEX IX_LECTURA_EN_REVISION     ON LECTURA (CASE WHEN ESTADO = 'EN_REVISION' THEN PERIODO END);

-- RF-09 / RN-21 / RN-31: jobs de alertas a 48 h, vencimiento y reconocimiento del silencio positivo
CREATE INDEX IX_PQR_PLAZO               ON PQR (ESTADO, FECHA_LIMITE_RESPUESTA);
CREATE INDEX IX_PQR_SILENCIO            ON PQR (
    CASE WHEN SILENCIO_POSITIVO = 'S' AND FECHA_RECONOCIMIENTO_SILENCIO IS NULL THEN FECHA_LIMITE_RECONOCIMIENTO END);

-- RF-12 / RN-07: job de cuotas vencidas
CREATE INDEX IX_CUOTA_VENCIMIENTO       ON CUOTA_ACUERDO (ESTADO, FECHA_VENCIMIENTO);

-- RN-36: órdenes pendientes por fecha límite (alerta de reconexión fuera de las 24 h)
CREATE INDEX IX_ORDEN_PENDIENTES        ON ORDEN_SERVICIO (CASE WHEN ESTADO = 'PENDIENTE' THEN FECHA_LIMITE END);

-- Bandeja de notificaciones pendientes de envío o reintento
CREATE INDEX IX_NOTIF_PENDIENTES        ON NOTIFICACION (ESTADO, PROXIMO_INTENTO);

-- RF-15 / CU-11: consulta del log por fecha, por entidad y por actor
