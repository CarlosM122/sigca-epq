-- ---------------------------------------------------------------------
-- 1. Unicidad condicional (reglas de negocio)
--    Oracle no indexa filas cuya expresión es NULL en todas las columnas,
--    así que el CASE limita la unicidad a las filas que cumplen la condición.
-- ---------------------------------------------------------------------

-- RN-01 / P-04: un solo contrato vigente (ACTIVO o SUSPENDIDO) por predio y tipo de servicio
CREATE UNIQUE INDEX UX_CONTRATO_VIGENTE ON CONTRATO_SERVICIO (
    CASE WHEN ESTADO IN ('ACTIVO','SUSPENDIDO') THEN PREDIO_ID END,
    CASE WHEN ESTADO IN ('ACTIVO','SUSPENDIDO') THEN TIPO_SERVICIO END);

-- Un medidor no puede estar en dos contratos vigentes
CREATE UNIQUE INDEX UX_CONTRATO_MEDIDOR_VIGENTE ON CONTRATO_SERVICIO (
    CASE WHEN ESTADO IN ('ACTIVO','SUSPENDIDO') THEN MEDIDOR_ID END);

-- Un solo medidor activo por predio y tipo de servicio
CREATE UNIQUE INDEX UX_MEDIDOR_ACTIVO ON MEDIDOR (
    CASE WHEN ESTADO = 'ACTIVO' THEN PREDIO_ID END,
    CASE WHEN ESTADO = 'ACTIVO' THEN TIPO_SERVICIO END);

-- Una sola tarifa abierta (sin fecha de fin) por servicio y municipio
CREATE UNIQUE INDEX UX_TARIFA_ABIERTA ON TARIFA (
    CASE WHEN VIGENTE_HASTA IS NULL THEN TIPO_SERVICIO END,
    CASE WHEN VIGENTE_HASTA IS NULL THEN MUNICIPIO_ID END);

-- Un solo factor abierto por municipio, servicio, uso y estrato
CREATE UNIQUE INDEX UX_FACTOR_ABIERTO ON FACTOR_SUBSIDIO (
    CASE WHEN VIGENTE_HASTA IS NULL THEN MUNICIPIO_ID END,
    CASE WHEN VIGENTE_HASTA IS NULL THEN TIPO_SERVICIO END,
    CASE WHEN VIGENTE_HASTA IS NULL THEN USO END,
    CASE WHEN VIGENTE_HASTA IS NULL THEN NVL(ESTRATO, 0) END);

-- P-05: una sola factura no anulada por usuario, predio y periodo (permite reexpedir tras anular)
CREATE UNIQUE INDEX UX_FACTURA_PREDIO_PERIODO ON FACTURA (
    CASE WHEN ESTADO <> 'ANULADA' THEN USUARIO_ID END,
    CASE WHEN ESTADO <> 'ANULADA' THEN PREDIO_ID END,
    CASE WHEN ESTADO <> 'ANULADA' THEN PERIODO END);

-- No se puede lanzar dos veces el lote de un mismo periodo (salvo que el anterior haya fallado)
CREATE UNIQUE INDEX UX_LOTE_PERIODO ON LOTE_FACTURACION (
    CASE WHEN ESTADO IN ('EN_PROCESO','COMPLETADO') THEN PERIODO END);

-- Un solo intento de pago en línea abierto por factura o cuota (evita doble cobro concurrente)
CREATE UNIQUE INDEX UX_TRANSACCION_FACTURA_ABIERTA ON TRANSACCION_PASARELA (
    CASE WHEN ESTADO = 'INICIADA' THEN FACTURA_ID END);
CREATE UNIQUE INDEX UX_TRANSACCION_CUOTA_ABIERTA ON TRANSACCION_PASARELA (
    CASE WHEN ESTADO = 'INICIADA' THEN CUOTA_ID END);

-- Un usuario no puede tener dos acuerdos de pago vigentes
CREATE UNIQUE INDEX UX_ACUERDO_VIGENTE ON ACUERDO_PAGO (
    CASE WHEN ESTADO = 'VIGENTE' THEN USUARIO_ID END);

-- Un usuario no puede tener dos procesos de cobro abiertos
CREATE UNIQUE INDEX UX_COBRO_ABIERTO ON COBRO_PERSUASIVO (
    CASE WHEN ESTADO IN ('ACTIVO','SUSPENDIDO') THEN USUARIO_ID END);

-- Una sola orden pendiente por contrato y tipo (suspensión o reconexión)
CREATE UNIQUE INDEX UX_ORDEN_PENDIENTE ON ORDEN_SERVICIO (
    CASE WHEN ESTADO = 'PENDIENTE' THEN CONTRATO_ID END,
    CASE WHEN ESTADO = 'PENDIENTE' THEN TIPO END);

-- Un solo token sin usar por cuenta y tipo
CREATE UNIQUE INDEX UX_TOKEN_PENDIENTE ON TOKEN_ACCESO (
    CASE WHEN USADO_EN IS NULL THEN USUARIO_ID END,
    CASE WHEN USADO_EN IS NULL THEN TIPO END);

